"""TensorFlow dataset loaders for the supported medical-image domains.

The module exposes individual loaders for the train, validation, and test
splits.  All locations and runtime settings are supplied by :mod:`config`.
"""

from __future__ import annotations

import logging
from pathlib import Path
from typing import Final

import tensorflow as tf

from config import CONFIG


LOGGER = logging.getLogger(__name__)
SUPPORTED_IMAGE_SUFFIXES: Final[frozenset[str]] = frozenset(
    {".bmp", ".gif", ".jpeg", ".jpg", ".png"}
)


def _count_images(directory: Path) -> int:
    """Return the number of TensorFlow-supported image files in a directory."""
    return sum(
        1
        for file_path in directory.rglob("*")
        if file_path.is_file() and file_path.suffix.lower() in SUPPORTED_IMAGE_SUFFIXES
    )


def _validate_directory(directory: Path, dataset_name: str, split_name: str) -> None:
    """Validate that a split directory exists and contains image files.

    Args:
        directory: Directory assigned to the requested split.
        dataset_name: User-facing dataset identifier.
        split_name: Requested data split.

    Raises:
        FileNotFoundError: If the split directory does not exist.
        ValueError: If the directory contains no supported image files.
    """
    if not directory.is_dir():
        raise FileNotFoundError(
            f"{split_name.title()} directory for '{dataset_name}' was not found: "
            f"{directory}"
        )

    if _count_images(directory) == 0:
        raise ValueError(
            f"{split_name.title()} directory for '{dataset_name}' contains no "
            f"supported image files: {directory}"
        )


def print_dataset_statistics(
    dataset: tf.data.Dataset,
    dataset_name: str,
    split_name: str,
    image_count: int,
) -> None:
    """Log class and image statistics for a loaded dataset.

    Args:
        dataset: Dataset returned by ``image_dataset_from_directory``.
        dataset_name: Dataset domain, such as ``"skin"``.
        split_name: Dataset split, such as ``"train"``.
        image_count: Number of discovered image files.
    """
    class_names = list(getattr(dataset, "class_names", []))
    message = "%s %s dataset statistics | classes: %d | images: %d | names: %s"
    values = (
        dataset_name.title(),
        split_name.title(),
        len(class_names),
        image_count,
        class_names,
    )
    LOGGER.info(message, *values)
    print(message % values)


def _load_dataset(
    dataset_name: str,
    split_name: str,
    *,
    shuffle: bool,
) -> tf.data.Dataset:
    """Create a configured ``tf.data.Dataset`` for one domain and split.

    The returned dataset carries a ``class_names`` attribute generated by
    Keras. Class ordering is alphabetical and is therefore stable when the
    class directories match across Train, Validation, and test.
    """
    normalized_name = dataset_name.strip().lower()
    directory = CONFIG.split_dir(normalized_name, split_name)
    _validate_directory(directory, normalized_name, split_name)
    image_count = _count_images(directory)

    try:
        dataset = tf.keras.utils.image_dataset_from_directory(
            directory,
            labels="inferred",
            label_mode="int",
            color_mode="rgb",
            batch_size=CONFIG.batch_size,
            image_size=CONFIG.image_size,
            shuffle=shuffle,
            seed=CONFIG.random_seed if shuffle else None,
        )
    except (OSError, tf.errors.OpError) as error:
        LOGGER.exception("Could not load %s split for '%s'.", split_name, normalized_name)
        raise RuntimeError(
            f"Unable to load {split_name} split for '{normalized_name}'."
        ) from error

    class_names = list(dataset.class_names)
    if not class_names:
        raise ValueError(f"No class directories were detected in: {directory}")

    if CONFIG.cache_datasets:
        dataset = dataset.cache()

    if shuffle:
        dataset = dataset.shuffle(
            buffer_size=min(CONFIG.shuffle_buffer_size, image_count),
            seed=CONFIG.random_seed,
            reshuffle_each_iteration=True,
        )

    dataset = dataset.prefetch(tf.data.AUTOTUNE)
    # Preserve Keras metadata after tf.data transformation calls.
    dataset.class_names = class_names
    print_dataset_statistics(dataset, normalized_name, split_name, image_count)
    return dataset


def load_train_dataset(dataset_name: str) -> tf.data.Dataset:
    """Load and optimize the training split for skin, eye, or oral disease.

    Args:
        dataset_name: One of ``"skin"``, ``"eye"``, or ``"oral"``.

    Returns:
        A batched, cached, shuffled, and prefetched TensorFlow dataset.
    """
    return _load_dataset(dataset_name, "train", shuffle=True)


def load_validation_dataset(dataset_name: str) -> tf.data.Dataset:
    """Load and optimize the validation split for a supported dataset domain."""
    return _load_dataset(dataset_name, "validation", shuffle=False)


def load_test_dataset(dataset_name: str) -> tf.data.Dataset:
    """Load and optimize the test split for a supported dataset domain."""
    return _load_dataset(dataset_name, "test", shuffle=False)
